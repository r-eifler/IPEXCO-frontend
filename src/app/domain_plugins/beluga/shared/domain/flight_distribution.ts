export function convertArrivalTime(value: number){
    const part1 = Math.floor(value);
    const part2 = value % 1

    const days = Math.floor(part1 / 24)
    const hours = part1 % 24
    const minutes = Math.floor(part2 * 60)

    return {days, hours, minutes}
}
